// יצירת 50 השלבים במפה
export function קבלשלבמפה(מספר: number): שלבמפהמידע {
  let שםאזור = 'אילת והדרום';
  let אייקוןאזור = '🌴';
  let ביטויים = ביטוייאילת;

  if (מספר >= 9 && מספר <= 16) {
    שםאזור = 'הנגב ומכתש רמון';
    אייקוןאזור = '🏜️';
    ביטויים = ביטויינגב;
  } else if (מספר >= 17 && מספר <= 25) {
    שםאזור = 'ירושלים והרי יהודה';
    אייקוןאזור = '🏰';
    ביטויים = ביטוייירושלים;
  } else if (מספר >= 26 && מספר <= 34) {
    שםאזור = 'תל אביב וגוש דן';
    אייקוןאזור = '🏙️';
    ביטויים = ביטוייתלאביב;
  } else if (מספר >= 35 && מספר <= 42) {
    שםאזור = 'חיפה והכרמל';
    אייקוןאזור = '🚢';
    ביטויים = ביטוייחיפה;
  } else if (מספר >= 43) {
    שםאזור = 'הגולן ופסגת החרמון';
    אייקוןאזור = '❄️';
    ביטויים = ביטוייחרמון;
  }

  // מהירות בסיס משתנה מ-3000ms בשלב 1 ועד 1000ms בשלב 50
  const מהירותבסיס = Math.max(3000 - מספר * 40, 950);
  const יעדפגיעות = Math.min(6 + Math.floor(מספר / 5), 14);

  return {
    מספרשלב: מספר,
    שםאזור,
    אייקוןאזור,
    תיאור: `שלב ${מספר} - חבר ${יעדפגיעות} ביטויים בהצלחה!`,
    ביטויים,
    יעדפגיעות,
    מהירותבסיס,
  };
}
