import type { קטגוריהסוג } from '../types';

// ─── פילטר קטגוריה ─────────────────────────────────────────────
export function פלטרלפיקטגוריה(קטגוריה: קטגוריהסוג): ביטוי[] {
  if (קטגוריה === 'הכל') return כלהביטויים;
  return כלהביטויים.filter((ב) => ב.קטגוריה === קטגוריה);
}

// ─── Seeded RNG לאתגר יומי ──────────────────────────────────────
function seededRandom(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 1664525 + 1013904223) & 0xffffffff;
    return ((s >>> 0) / 0xffffffff);
  };
}

export function ביטוייםיומיים(): ביטוי[] {
  const today = new Date();
  const seed = today.getFullYear() * 10000 + (today.getMonth() + 1) * 100 + today.getDate();
  const rng = seededRandom(seed);

  const shuffled = [...כלהביטויים]
    .map((ב, i) => ({ ב, sort: rng() }))
    .sort((a, b) => a.sort - b.sort)
    .map(({ ב }) => ב);

  return shuffled.slice(0, 15);
}

// ─── בחירה אקראית ──────────────────────────────────────────────
export function בחרביטויאקראי(
  שימשו: Set<number>,
  מקור: ביטוי[] = כלהביטויים
): { ביטוי: ביטוי; אינדקס: number } {
  const זמינים = מקור
    .map((_, i) => i)
    .filter((i) => !שימשו.has(i));

  if (זמינים.length === 0) {
    const idx = Math.floor(Math.random() * מקור.length);
    return { ביטוי: מקור[idx], אינדקס: idx };
  }

  const אינדקס = זמינים[Math.floor(Math.random() * זמינים.length)];
  return { ביטוי: מקור[אינדקס], אינדקס };
}
