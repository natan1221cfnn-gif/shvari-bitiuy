  עדכןביטוי: () => void;
  טפלבהצלחה: () => { מכפיל: number; ניקודחדש: number; מטבעותנוספו: number };
  טפלבפספוס: (ביטוי: ביטוי) => boolean;
  טפלבכמעט: () => void;
  טפלבפצצה: () => void;
  עדכןסטטוס: (סטטוס: סטטוסמשחק) => void;
