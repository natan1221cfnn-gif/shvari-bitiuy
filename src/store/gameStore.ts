function טעןשםשחקן(): string {
  try {
    const שמור = localStorage.getItem('שברי-ביטוי-שם-שחקן');
    if (שמור && שמור.trim()) return שמור;
  } catch { /* ignore */ }
  const מסאקראי = Math.floor(1000 + Math.random() * 9000);
  const שםדיפולט = `שחקן#${מסאקראי}`;
  try {
    localStorage.setItem('שברי-ביטוי-שם-שחקן', שםדיפולט);
  } catch { /* ignore */ }
  return שםדיפולט;
}

function טעןמטבעות(): number {
  try {
    return parseInt(localStorage.getItem('שברי-ביטוי-מטבעות') || '50', 10);
  } catch { return 50; }
}

function טעןסקיןפעיל(): סוגסקין {
  try {
    return (localStorage.getItem('שברי-ביטוי-סקין') as סוגסקין) || 'קלאסי';
  } catch { return 'קלאסי'; }
}

function טעןסקיניםפתוחים(): סוגסקין[] {
  try {
    const שמור = localStorage.getItem('שברי-ביטוי-סקינים-פתוחים');
    if (שמור) return JSON.parse(שמור);
  } catch { /* ignore */ }
  return ['קלאסי'];
}

function טעןגלגללאחרונה(): number {
  try {
    return parseInt(localStorage.getItem('שברי-ביטוי-גלגל') || '0', 10);
  } catch { return 0; }
}

function טעןהגדרות(): הגדרות {
  try {
    const שמור = localStorage.getItem('שברי-ביטוי-הגדרות');
    if (שמור) return { ...הגדרותברירתמחדל, ...JSON.parse(שמור) };
  } catch { /* ignore */ }
  return הגדרותברירתמחדל;
}

function טעןשיאים(): שיא[] {
  try {
    const שמור = localStorage.getItem('שברי-ביטוי-שיאים');
    if (שמור) return JSON.parse(שמור);
  } catch { /* ignore */ }
  return [];
}

function טעןשיאאישי(): number {
  try {
    return parseInt(localStorage.getItem('שברי-ביטוי-שיא') || '0', 10);
  } catch { /* ignore */ }
  return 0;
}

function חשבמהירות(שלב: number, רמה: רמתקושי, האטה: boolean, טירוף: boolean): number {
  if (טירוף) {
    return Math.max(1400 - שלב * 35, 750);
  }
  const בסיס = רמה === 'קל' ? 3800 : רמה === 'בינוני' ? 2600 : 1800;
  const הפחתה = שלב * (רמה === 'קל' ? 25 : רמה === 'בינוני' ? 45 : 65);
  const מחושב = Math.max(בסיס - הפחתה, רמה === 'קל' ? 2000 : רמה === 'בינוני' ? 1200 : 800);
  return האטה ? מחושב * 1.6 : מחושב;
}

function בחרבלוקמיוחדאקראי(): סוגבלוקמיוחד {
  const rand = Math.random();
  if (rand < 0.12) return 'זהב';
  if (rand < 0.22) return 'האטה';
  if (rand < 0.32) return 'פצצה';
  return 'רגיל';
}

function בחרמסלולאקראי(שלב: number): סוגמסלול {
  if (שלב <= 2) return 'ישר';
  const rand = Math.random();
  if (rand < 0.35) return 'אלכסון';
  if (rand < 0.7) return 'קשת';
  if (rand < 0.88) return 'סחרור';
  return 'ישר';
}

